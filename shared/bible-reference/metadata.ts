const BOOKS_BY_ID = new Map(BIBLE_BOOKS.map((book) => [book.bookId, book]));

export function normalizeBibleBookKey(value: string): string {
  return value.normalize("NFKC").trim().replace(/[.\s]/gu, "");
}

const BOOKS_BY_KOREAN_KEY = new Map<string, BibleBookMetadata>();
for (const book of BIBLE_BOOKS) {
  for (const name of [book.canonicalKoreanName, ...book.aliases]) {
    const key = normalizeBibleBookKey(name);
    const existing = BOOKS_BY_KOREAN_KEY.get(key);
    if (existing !== undefined && existing.bookId !== book.bookId) {
      throw new Error(`성경 책 별칭이 중복되었습니다: ${key}`);
    }
    BOOKS_BY_KOREAN_KEY.set(key, book);
  }
}

export function getBibleBook(bookId: BibleBookId): BibleBookMetadata {
  const book = BOOKS_BY_ID.get(bookId);
  if (book === undefined) {
    throw new Error(`등록되지 않은 성경 책 ID입니다: ${bookId}`);
  }
  return book;
}

export function findBibleBookByKoreanName(value: string): BibleBookMetadata | undefined {
  return BOOKS_BY_KOREAN_KEY.get(normalizeBibleBookKey(value));
}

export function getVerseCount(bookId: BibleBookId, chapter: number): number | undefined {
  return getBibleBook(bookId).verseCounts[chapter - 1];
}
