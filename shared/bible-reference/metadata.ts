import type { BibleBookId } from "./types";

export interface BibleBookMetadata {
  readonly aliases: readonly string[];
  readonly bookId: BibleBookId;
  readonly canonicalKoreanName: string;
  readonly canonicalOrder: number;
  readonly chapterCount: number;
  readonly testament: "old" | "new";
  readonly verseCounts: readonly number[];
}

function defineBook(
  bookId: BibleBookId,
  canonicalKoreanName: string,
  aliases: readonly string[],
  verseCounts: readonly number[],
  canonicalOrder: number,
): BibleBookMetadata {
  return Object.freeze({
    aliases: Object.freeze([...aliases]),
    bookId,
    canonicalKoreanName,
    canonicalOrder,
    chapterCount: verseCounts.length,
    testament: canonicalOrder <= 39 ? "old" : "new",
    verseCounts: Object.freeze([...verseCounts]),
  });
}

